#!/usr/bin/env node
/**
 * Bump admin panel display version (1.11, 1.12, …) before each production build.
 * Updates lib/generated/admin-panel-version.ts and increments version/admin-panel.json.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const jsonPath = path.join(root, 'version/admin-panel.json');
const outPath = path.join(root, 'lib/generated/admin-panel-version.ts');

const data = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
const build = Number(data.build);
if (!Number.isFinite(build) || build < 1) {
  throw new Error('version/admin-panel.json must have a positive numeric "build" field');
}

const version = `1.${build}`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(
  outPath,
  `/** Auto-generated by scripts/bump-admin-panel-version.mjs — do not edit */\nexport const ADMIN_PANEL_VERSION = '${version}';\n`
);

data.build = build + 1;
fs.writeFileSync(jsonPath, `${JSON.stringify(data, null, 2)}\n`);

console.log(`[admin-version] panel v${version} (next build → 1.${build + 1})`);
